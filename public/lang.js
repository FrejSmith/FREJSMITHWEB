function getPreferredLanguage() {
    const urlLang = new URLSearchParams(window.location.search).get('lang');
    if (urlLang && translations[urlLang]) {
        localStorage.setItem('siteLang', urlLang);
        return urlLang;
    }
    const stored = localStorage.getItem('siteLang');
    if (stored && translations[stored]) {
        return stored;
    }
    return 'fr';
}

function setLanguage(lang) {
    if (!translations[lang]) {
        lang = 'fr';
    }
    localStorage.setItem('siteLang', lang);
    const url = new URL(window.location.href);
    url.searchParams.set('lang', lang);
    window.history.replaceState({}, '', url.toString());
    translatePage(lang);
}

function translatePage(lang) {
    const trans = translations[lang];
    document.querySelectorAll('[data-i18n]').forEach((element) => {
        const key = element.dataset.i18n;
        if (trans[key]) {
            if (element.tagName === 'INPUT' || element.tagName === 'TEXTAREA') {
                element.placeholder = trans[key];
            } else {
                element.innerText = trans[key];
            }
        }
    });

    document.querySelectorAll('[data-i18n-placeholder]').forEach((element) => {
        const key = element.dataset.i18nPlaceholder;
        if (trans[key]) {
            element.placeholder = trans[key];
        }
    });

    document.querySelectorAll('[data-i18n-service-title]').forEach((element) => {
        const serviceKey = element.dataset.i18nServiceTitle;
        const serviceData = serviceTranslations[serviceKey] && serviceTranslations[serviceKey][lang];
        if (serviceData && serviceData.name) {
            element.innerText = serviceData.name;
        }
    });

    document.querySelectorAll('[data-i18n-service-desc]').forEach((element) => {
        const serviceKey = element.dataset.i18nServiceDesc;
        const serviceData = serviceTranslations[serviceKey] && serviceTranslations[serviceKey][lang];
        if (serviceData && serviceData.desc) {
            element.innerText = serviceData.desc;
        }
    });

    document.querySelectorAll('[data-i18n-service-long-desc]').forEach((element) => {
        const serviceKey = element.dataset.i18nServiceLongDesc;
        const serviceData = serviceTranslations[serviceKey] && serviceTranslations[serviceKey][lang];
        if (serviceData && serviceData.long_desc) {
            element.innerText = serviceData.long_desc;
        }
    });

    const titleKey = document.body.dataset.pageTitleKey;
    if (titleKey && trans[titleKey]) {
        document.title = trans[titleKey];
    }

    const selector = document.getElementById('languageSelector');
    if (selector) {
        selector.value = lang;
    }
}

function initLanguageSelector() {
    const selector = document.getElementById('languageSelector');
    if (!selector) {
        return;
    }
    selector.addEventListener('change', (event) => {
        setLanguage(event.target.value);
    });
}

function initNavDropdowns() {
    const dropdowns = document.querySelectorAll('.nav-dropdown');
    if (!dropdowns.length) return;

    dropdowns.forEach((dd) => {
        const trigger = dd.querySelector('a');
        if (!trigger) return;
        trigger.addEventListener('click', (e) => {
            // prevent default anchor jump if it links to an anchor
            e.preventDefault();
            dd.classList.toggle('open');
        });
    });

    // close dropdowns on outside click
    document.addEventListener('click', (e) => {
        dropdowns.forEach((dd) => {
            if (!dd.contains(e.target)) {
                dd.classList.remove('open');
            }
        });
    });
}

window.addEventListener('DOMContentLoaded', () => {
    initLanguageSelector();
    initNavDropdowns();
    setLanguage(getPreferredLanguage());
});
